export function validateHeadline(headline: string, consulting: boolean) {
  const plain = headline.replace(/\*\*/g, "").trim().replace(/[.!?。]+$/, "");
  if (!plain || [...plain].length > 75)
    throw Error("헤드라인을 글자 수 제한 안으로 줄여 주세요.");
  if (consulting && (!/(니다|까요|인가요|는가|일까)$/.test(plain) || plain.split("\n").length > 2))
    throw Error("컨설팅 헤드라인은 2줄 이내의 자연스러운 존댓말 문장으로 써 주세요.");
}
